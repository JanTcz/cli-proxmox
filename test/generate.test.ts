// UC-1 — the client is generated from Proxmox's schema (docs/features/01-read.md): paths as properties, `{param}` as `$(value)`,
// methods `$get`/`$post`/`$put`/`$delete` typed from the schema, its quirks taken as Proxmox writes them; the committed client is
// the generator's output for the vendored schema, whose checksum is recorded.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { generate, type SchemaNode, SCHEMA_SHA256, SCHEMA_VERSION } from '../src/api/generate.ts';

const ROOT = join(import.meta.dirname, '..');

const SCHEMA: SchemaNode[] = [{
  path: '/nodes', text: 'nodes',
  info: { GET: { method: 'GET', description: 'Cluster node index.', parameters: { additionalProperties: 0 },
    returns: { type: 'array', items: { type: 'object', properties: { node: { type: 'string', description: 'The node.' }, maxcpu: { type: 'integer', optional: 1 } } } } } },
  children: [{
    path: '/nodes/{node}', text: '{node}',
    children: [{
      path: '/nodes/{node}/qemu', text: 'qemu',
      children: [{
        path: '/nodes/{node}/qemu/{vmid}', text: '{vmid}',
        info: { DELETE: { method: 'DELETE', description: 'Destroy the VM */ and all used/owned volumes.',
          parameters: { properties: { node: { type: 'string' }, vmid: { type: 'integer' }, purge: { type: 'boolean', optional: '1' } } }, returns: { type: 'string' } } },
        children: [{
          path: '/nodes/{node}/qemu/{vmid}/status', text: 'status',
          children: [{
            path: '/nodes/{node}/qemu/{vmid}/status/start', text: 'start',
            info: { POST: { method: 'POST', description: 'Start virtual machine.', parameters: { properties: {
              node: { type: 'string' }, vmid: { type: 'integer', minimum: '100' },
              timeout: { type: 'integer', optional: 1, minimum: '0', maximum: 86_400 },
              'force-cpu': { type: 'string', optional: 1 }, migration_type: { type: 'string', enum: ['secure', 'insecure'], optional: 1 },
            } }, returns: { type: 'string' } } },
          }],
        }, {
          path: '/nodes/{node}/qemu/{vmid}/config', text: 'config',
          info: { PUT: { method: 'PUT', parameters: { properties: { node: { type: 'string' }, vmid: { type: 'integer' }, onboot: { type: 'boolean', optional: 1 },
            tags: { type: 'array', items: { type: 'string' }, optional: 1 } } }, returns: { type: 'null' } } },
        }],
      }],
    }],
  }],
}];

test('UC-1: a path\'s segments are properties, a {param} is $(value), each method is typed from the schema', () => {
  const out = generate(SCHEMA, '9.9.9');
  assert.match(out, /^\/\/ Generated by scripts\/generate\.ts from Proxmox VE 9\.9\.9's API schema\. Do not edit\./u);
  assert.match(out, /export interface Pve \{/u);
  assert.match(out, /"nodes": \{/u, 'a segment is a property');
  assert.match(out, /\/\*\* Cluster node index\. \*\/\n\s*\$get\(params\?: Record<string, never>\): Promise<\{ "node": string; "maxcpu"\?: number \}\[\]>;/u);
  assert.match(out, /\$\(node: string \| number\): \{/u, '{node} is $(node)');
  assert.match(out, /\$\(vmid: string \| number\): \{/u);
  assert.match(out, /\$post\(params\?: \{ "timeout"\?: number; "force-cpu"\?: string; "migration_type"\?: "secure" \| "insecure" \}\): Promise<string>;/u,
    'the path\'s own parameters are left out; optional ones optional; an enum a union; a name that is no identifier quoted');
  assert.match(out, /\$delete\(params\?: \{ "purge"\?: boolean \}\): Promise<string>;/u, 'optional written "1" is optional');
  assert.match(out, /Destroy the VM \*\\\/ and all/u, 'a comment cannot be closed by the description');
  assert.match(out, /\$put\(params\?: \{ "onboot"\?: boolean; "tags"\?: string\[\] \}\): Promise<null>;/u);
});

test('UC-1: a method with a required parameter takes its parameters as required', () => {
  const schema: SchemaNode[] = [{ path: '/cluster', text: 'cluster', children: [{ path: '/cluster/nextid', text: 'nextid',
    info: { POST: { method: 'POST', parameters: { properties: { vmid: { type: 'integer' }, note: { type: 'string', optional: 1 } } }, returns: {} } } }] }];
  assert.match(generate(schema, '1'), /\$post\(params: \{ "vmid": number; "note"\?: string \}\): Promise<unknown>;/u);
});

test('UC-1: answers typed by their schema — objects without properties, nested arrays, unknown types', () => {
  const schema: SchemaNode[] = [{ path: '/a', text: 'a', info: { GET: { method: 'GET', returns: { type: 'object' } } }, children: [
    { path: '/a/b', text: 'b', info: { GET: { method: 'GET', returns: { type: 'array', items: { type: 'array' } } } } },
    { path: '/a/c', text: 'c', info: { GET: { method: 'GET', returns: { type: 'number' } } } },
    { path: '/a/d', text: 'd', info: { GET: { method: 'GET', returns: { type: 'any' } } } },
  ] }];
  const out = generate(schema, '1');
  assert.match(out, /\$get\(params\?: Record<string, never>\): Promise<Record<string, unknown>>;/u);
  assert.match(out, /"b": \{\n\s*\$get\(params\?: Record<string, never>\): Promise<unknown\[\]\[\]>;/u);
  assert.match(out, /"c": \{\n\s*\$get\(params\?: Record<string, never>\): Promise<number>;/u);
  assert.match(out, /"d": \{\n\s*\$get\(params\?: Record<string, never>\): Promise<unknown>;/u);
});

test('UC-1: two {param} children of one path cannot be told apart — refused by name', () => {
  const schema: SchemaNode[] = [{ path: '/x', text: 'x', children: [{ path: '/x/{a}', text: '{a}' }, { path: '/x/{b}', text: '{b}' }] }];
  assert.throws(() => generate(schema, '1'), /\/x: more than one \{param\} child: \{a\}, \{b\}/u);
});

test('UC-1: the committed client is the generator\'s output for the vendored schema, whose checksum is recorded', () => {
  const raw = readFileSync(join(ROOT, 'schema', `pve-${SCHEMA_VERSION}.json`));
  assert.equal(createHash('sha256').update(raw).digest('hex'), SCHEMA_SHA256, 'the vendored schema is the one recorded');
  const committed = readFileSync(join(ROOT, 'src', 'api', 'pve.gen.ts'), 'utf8');
  assert.equal(committed, generate(JSON.parse(raw.toString('utf8')) as SchemaNode[], SCHEMA_VERSION), 'run npm run generate');
});
