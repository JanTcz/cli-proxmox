// The client's types, generated from Proxmox's own API schema (UC-1): the API viewer's `apidoc.js` as JSON, vendored in schema/ and
// pinned by its checksum. A path's segments are properties, a `{param}` segment is `$(value)`, each method `$get`/`$post`/`$put`/
// `$delete`, typed from the schema — the shape of the community client proxmox-api, written from Proxmox's schema alone.

// The schema the committed client was generated from: the lab host's Proxmox VE, its apidoc.js as JSON.
export const SCHEMA_VERSION = '9.2.20';
export const SCHEMA_SHA256 = '80d1a2202d5ae3b344011ac5359550ab6aff8bde07b7f454a93d3b9b8768465b';

// What the schema says of a value, as far as the types read it. Proxmox writes `optional` as 1 or "1", and bounds sometimes as strings.
export type SchemaType = {
  type?: string; optional?: number | string; enum?: string[]; items?: SchemaType; properties?: Record<string, SchemaType>;
  description?: string; minimum?: number | string; maximum?: number | string;
};
export type SchemaMethod = { method: string; description?: string; parameters?: { additionalProperties?: number; properties?: Record<string, SchemaType> }; returns?: SchemaType };
export type SchemaNode = { path: string; text: string; info?: Partial<Record<HttpMethod, SchemaMethod>>; children?: SchemaNode[] };
type HttpMethod = 'GET' | 'POST' | 'PUT' | 'DELETE';

const METHODS: [HttpMethod, string][] = [['GET', '$get'], ['POST', '$post'], ['PUT', '$put'], ['DELETE', '$delete']];
const IDENTIFIER = /^[A-Za-z_]\w*$/u;
const PARAM = /^\{(.+)\}$/u;

const optional = (type: SchemaType): boolean => type.optional === 1 || type.optional === '1';
const quoted = (name: string): string => JSON.stringify(name);
const grouped = (type: string): string => (type.includes(' | ') ? `(${type})` : type);

function objectOf(properties: Record<string, SchemaType>, leftOut: readonly string[] = []): string {
  const fields = Object.entries(properties).filter(([name]) => !leftOut.includes(name))
    .map(([name, type]) => `${quoted(name)}${optional(type) ? '?' : ''}: ${typeOf(type)}`);
  return fields.length === 0 ? 'Record<string, never>' : `{ ${fields.join('; ')} }`;
}

export function typeOf(type: SchemaType | undefined): string {
  if (type?.enum) return type.enum.map((value) => quoted(value)).join(' | ');
  switch (type?.type) {
    case 'string': return 'string';
    case 'integer':
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${grouped(typeOf(type.items))}[]`;
    case 'object': return type.properties ? objectOf(type.properties) : 'Record<string, unknown>';
    default: return 'unknown';
  }
}

// A description as one comment line that cannot close itself.
const comment = (text: string | undefined): string[] => (text ? [`/** ${text.split('\n')[0]!.replaceAll('*/', '*\\/')} */`] : []);

function methodLines(node: SchemaNode, pathParams: readonly string[]): string[] {
  return METHODS.flatMap(([http, name]) => {
    const method = node.info?.[http];
    if (!method) return [];
    const properties = method.parameters?.properties ?? {};
    const required = Object.entries(properties).some(([param, type]) => !pathParams.includes(param) && !optional(type));
    const lines = comment(method.description);
    lines.push(`${name}(params${required ? '' : '?'}: ${objectOf(properties, pathParams)}): Promise<${typeOf(method.returns)}>;`);
    return lines;
  });
}

function members(node: SchemaNode, pathParams: readonly string[]): string[] {
  const children = node.children ?? [];
  const dynamic = children.filter((child) => PARAM.test(child.text));
  if (dynamic.length > 1) throw new Error(`${node.path}: more than one {param} child: ${dynamic.map((child) => child.text).join(', ')}`);
  const nested = (child: SchemaNode, head: string, params: readonly string[]) => [`${head} {`, ...members(child, params).map((line) => `  ${line}`), '};'];
  return [
    ...methodLines(node, pathParams),
    ...children.filter((child) => !PARAM.test(child.text)).flatMap((child) => nested(child, `${quoted(child.text)}:`, pathParams)),
    ...dynamic.flatMap((child) => {
      const param = PARAM.exec(child.text)![1]!;
      return nested(child, `$(${IDENTIFIER.test(param) ? param : 'value'}: string | number):`, [...pathParams, param]);
    }),
  ];
}

export function generate(schema: SchemaNode[], version: string): string {
  const root: SchemaNode = { path: '', text: '', children: schema };
  return [
    `// Generated by scripts/generate.ts from Proxmox VE ${version}'s API schema. Do not edit.`,
    'export interface Pve {',
    ...members(root, []).map((line) => `  ${line}`),
    '}',
    '',
  ].join('\n');
}
